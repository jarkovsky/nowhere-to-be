import { menuAction } from './menu-helpers.mjs';
import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
const browser=await chromium.launch({channel:'chrome',headless:true});
const errors=[];
const captureErrors=page=>page.on('pageerror',error=>errors.push(error.message));
const read=page=>page.evaluate(()=>window.__littleWilds.getState());
const url=process.env.GAME_URL||'http://localhost:5173';
await mkdir('artifacts',{recursive:true});
try {
  const desktop=await browser.newPage({viewport:{width:1440,height:900}});captureErrors(desktop);
  await desktop.goto(url);await desktop.getByRole('button',{name:'Let’s wander'}).waitFor();
  await desktop.screenshot({path:'artifacts/desktop-welcome.png'});
  await desktop.getByRole('button',{name:'Let’s wander'}).click();
  const origin=await read(desktop);
  await desktop.keyboard.down('ArrowUp');await desktop.waitForTimeout(1200);
  await desktop.keyboard.down('ArrowLeft');await desktop.waitForTimeout(700);
  await desktop.keyboard.up('ArrowLeft');await desktop.keyboard.up('ArrowUp');
  const moving=await read(desktop);assert.ok(moving.distance>origin.distance+5);assert.ok(moving.heading>origin.heading+.1);
  await desktop.waitForTimeout(2800);assert.equal((await read(desktop)).speed,0);
  await menuAction(desktop,/Little explorer/);await desktop.waitForTimeout(1400);assert.ok((await read(desktop)).speed>3);
  await desktop.keyboard.down('Space');await desktop.waitForTimeout(1300);assert.equal((await read(desktop)).speed,0);await desktop.keyboard.up('Space');
  await desktop.keyboard.press('Escape');assert.ok((await read(desktop)).paused);
  const paused=await read(desktop);await desktop.waitForTimeout(300);assert.equal((await read(desktop)).distance,paused.distance);
  await desktop.keyboard.press('Escape');assert.equal((await read(desktop)).paused,false);
  await menuAction(desktop,/Little explorer/);await desktop.keyboard.press('r');
  assert.equal((await read(desktop)).x,origin.x);assert.equal((await read(desktop)).z,origin.z);
  await desktop.waitForTimeout(1000);await desktop.screenshot({path:'artifacts/desktop-driving.png'});
  console.log('PASS desktop: acceleration, steering, automatic stop, explorer, brake, Escape pause/resume, rescue');
  await menuAction(desktop,/Change sky/);await desktop.waitForTimeout(1600);
  assert.equal((await read(desktop)).atmosphere.preset,'sunset');
  await menuAction(desktop,/Change sky/);await desktop.waitForTimeout(4200);
  const night=await read(desktop);assert.ok(night.atmosphere.day<.1);assert.ok(night.atmosphere.headlightIntensity>40);
  await desktop.screenshot({path:'artifacts/desktop-night.png'});
  await menuAction(desktop,/Change sky/);await desktop.waitForTimeout(3000);
  assert.ok((await read(desktop)).atmosphere.rain>.8);
  await desktop.screenshot({path:'artifacts/desktop-rain.png'});
  assert.ok((await read(desktop)).wildlife.encounters>0);
  console.log('PASS discoveries: sunset, night, headlights, rain, and wildlife encounter');
  const context=await browser.newContext({viewport:{width:390,height:844},deviceScaleFactor:2,isMobile:true,hasTouch:true});
  const phone=await context.newPage();captureErrors(phone);await phone.goto(url);await phone.getByRole('button',{name:'Let’s wander'}).click();
  const cdp=await context.newCDPSession(phone);
  const center=async(name,id)=>{const r=await phone.getByRole('button',{name,exact:true}).boundingBox();assert.ok(r&&r.width>=44&&r.height>=44);return {x:r.x+r.width/2,y:r.y+r.height/2,id};};
  const forward=await center('Drive forward',1),left=await center('Steer left',2);
  await cdp.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[forward,left]});
  await phone.waitForTimeout(1300);const touch=await read(phone);assert.equal(touch.input.forward,true);assert.equal(touch.input.left,true);assert.ok(touch.distance>4);assert.ok(touch.heading>origin.heading+.15);
  await cdp.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[]});
  await phone.waitForTimeout(2700);const released=await read(phone);assert.equal(released.speed,0);assert.equal(released.input.forward,false);assert.equal(released.input.left,false);
  await cdp.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[forward]});await phone.waitForTimeout(300);await cdp.send('Input.dispatchTouchEvent',{type:'touchCancel',touchPoints:[]});assert.equal((await read(phone)).input.forward,false);
  await menuAction(phone,/Back to the meadow/);await phone.waitForTimeout(600);
  assert.equal(await phone.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
  await phone.screenshot({path:'artifacts/phone-driving.png'});
  await phone.setViewportSize({width:844,height:390});await phone.waitForTimeout(400);
  const screen=await phone.evaluate(()=>[innerWidth,innerHeight]);
  for(const name of ['Steer left','Steer right','Drive forward','Reverse','Brake']){const r=await phone.getByRole('button',{name,exact:true}).boundingBox();assert.ok(r&&r.x>=0&&r.y>=0&&r.x+r.width<=screen[0]&&r.y+r.height<=screen[1]);}
  console.log('PASS phone: real two-finger acceleration + steering, release, touch cancellation, rescue, portrait and landscape layouts');
  await phone.setViewportSize({width:1024,height:768});await phone.waitForTimeout(400);
  assert.ok(await phone.getByRole('button',{name:'Drive forward',exact:true}).isVisible());
  await phone.screenshot({path:'artifacts/tablet-driving.png'});
  console.log('PASS tablet: large touch controls visible at 1024 × 768');
  assert.deepEqual(errors,[]);console.log('PASS no browser runtime errors');
}finally{await browser.close();}
